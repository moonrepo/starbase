// Murex is the one shell this harness cannot drive. Its line editor swallows
// the first Enter of a session and then appends anything typed after it to the
// line it is still holding, so a step either never runs or runs with the next
// step's text glued to its arguments. Disabling hints and the autocomplete
// timeouts gets as far as a correct activation (`S1 foo=123`) before the next
// step is mangled. The non-interactive suite still covers murex, and the
// `onPrompt` registration is covered by its snapshot.
#[test]
#[ignore = "murex's line editor cannot be driven through a pty, see the comment above"]
fn murex_activates_and_deactivates() {
    run_case(Case {
        shell: ShellType::Murex,
        term: "xterm-256color",
        bin: "murex",
        // Murex's line editor treats a typed multi-line command as a paste and
        // asks about it, so the hook is loaded at startup, as a profile would
        args: |root| {
            vec![
                "-quiet".into(),
                "-c".into(),
                format!(
                    "config set shell hint-text-enabled false; \
                     config set shell autocomplete-soft-timeout 0; \
                     config set shell autocomplete-hard-timeout 0; \
                     source {root}/hook.mx"
                ),
                "-i".into(),
            ]
        },
        extension: "mx",
        evaluate: None,
        deactivate_call: "_starbase_deactivate",
        activates_on_prompt: true,
        defers_statements: false,
    });
}

